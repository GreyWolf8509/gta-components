// Regenerates media/glyphs.js: the counter's outlines for the Three.js extrusion. Needs fontkit (npm i fontkit).
//   FONT=../assets/fonts/Inter-normal.woff2 AXES='{"wght":900,"opsz":32}' node gen-glyphs.js > glyphs.js
// Digits are the TABULAR figures (OpenType tnum), so every digit column has the same advance.
// Output: window.LVL_GLYPHS = {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX, inkMinY, inkMaxY]}, k:{pair:kern}}
// path = SVG commands in font units, y-down (baseline 0, cap top at -cap).
const fontkit = require(process.env.FONTKIT || 'fontkit');
const f = fontkit.openSync(process.env.FONT);
const v = f.getVariation(JSON.parse(process.env.AXES));
const chars = "LVEUPMAX!0123456789,+ ";
const r = (x) => Math.round(x);
// The variable font keeps overlapping contours (stem + flag, two strokes of the V, the P's stem through its bowl, the 4's stem),
// which extrude as grooves and z-fighting seams. These outlines are the same glyphs with the overlaps removed by hand.
const FIX = {
  'P': 'M80 0L80 -1490L713 -1490Q891 -1490 1021 -1427Q1151 -1363 1222 -1247Q1292 -1130 1292 -970Q1292 -811 1222 -694Q1151 -577 1021 -514Q891 -450 713 -450L496 -450L496 0Z' +
       'M496 -792L682 -792Q745 -792 791 -814Q836 -836 861 -876Q886 -916 886 -970Q886 -1025 861 -1065Q836 -1104 791 -1126Q745 -1148 682 -1148L496 -1148Z',
  'V': 'M500 0L0 -1490L458 -1490L631 -912Q687 -724 739 -536L779 -391L816 -536Q865 -724 919 -912L1084 -1490L1536 -1490L1052 0Z',
  '1': 'M169 0L169 -322L517 -322L517 -1125L515 -1125L183 -922L183 -1266L549 -1490L917 -1490L917 -322L1200 -322L1200 0Z',
  '4': 'M18 -288L18 -602L625 -1490L1136 -1490L1136 -594L1302 -594L1302 -288L1136 -288L1136 0L746 0L746 -288Z' +
       'M746 -1118L393 -596L393 -594L746 -594Z'
};

const g = {};
for (const ch of chars) {
  const run = v.layout(ch, /[0-9]/.test(ch) ? ['tnum'] : []);
  const gl = run.glyphs[0], adv = run.positions[0].xAdvance;
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox;
  let path = FIX[ch] || cmds;
  if (ch === '8') path = path.replace('437 -772L437 -771Q', '437 -772Q').replace('883 -771L883 -772Q', '883 -771Q');
  g[ch] = [r(adv), path, ch === ' ' ? 0 : r(b.minX), ch === ' ' ? 0 : r(b.maxX), ch === ' ' ? 0 : r(b.minY), ch === ' ' ? 0 : r(b.maxY)];
}
const k = {};
const L = "LVEUPMAX!";
for (const a of L) for (const b of L) {
  const lay = v.layout(a + b);
  const kern = r(lay.positions[0].xAdvance - v.glyphForCodePoint(a.codePointAt(0)).advanceWidth);
  if (kern) k[a + b] = kern;
}
const cap = r(v.glyphForCodePoint(72).bbox.maxY);
process.stdout.write('/* ' + (process.env.FONT || '').split('/').pop() + ' ' + process.env.AXES + ' outlines (OFL), generated by gen-glyphs.js with fontkit. */\n' +
  'window.LVL_GLYPHS = ' + JSON.stringify({ upm: f.unitsPerEm, cap, g, k }) + ';\n');
