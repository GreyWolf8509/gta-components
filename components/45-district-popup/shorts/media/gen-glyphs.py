#!/usr/bin/env python3
"""Builds media/script-glyphs.js: single-line (centre-stroke) script glyphs for the 3D write-on.
Source: the EMS SVG stroke fonts (gitlab.com/oskay/svg-fonts, SIL OFL 1.1, see OFL-EMS.txt):
  EMS Allure = a single-line derivative of Allura (Rob Leuschke, TypeSETit), EMS Brush = of Alex Brush, EMS Decorous Script = of Petit Formal Script (Impallari Type).
Usage: python3 gen-glyphs.py <svg-fonts-dir>/fonts/EMS  > script-glyphs.js"""
import re, sys, json, os
def load(path):
    s = open(path).read()
    g = {}
    for m in re.finditer(r'<glyph\s+([^>]*?)/>', s, re.S):
        a = m.group(1)
        u = re.search(r'unicode="([^"]*)"', a)
        if not u: continue
        u = re.sub(r'&#x([0-9a-fA-F]+);', lambda k: chr(int(k.group(1), 16)), u.group(1))
        u = u.replace('&amp;', '&').replace('&lt;', '<').replace('&gt;', '>').replace('&quot;', '"').replace('&apos;', "'")
        if len(u) != 1 or not (32 <= ord(u) < 127 or u in 'éèáàñüöä'): continue
        adv = re.search(r'horiz-adv-x="([^"]*)"', a)
        d = re.search(r'\sd="([^"]*)"', ' ' + a)
        g[u] = [round(float(adv.group(1)), 1) if adv else 378, d.group(1).strip() if d else '']
    return g
src = sys.argv[1]
out = {'upm': 1000}
for key, fn in [('allure', 'EMSAllure.svg'), ('brush', 'EMSBrush.svg'), ('decorous', 'EMSDecorousScript.svg')]:
    out[key] = load(os.path.join(src, fn))
print('/* Single-line script glyphs (centre strokes, font units, y up, upm 1000) for media/script3d.js.\n'
      '   EMS Allure (from Allura, Rob Leuschke / TypeSETit) and EMS Brush (from Alex Brush), SVG stroke conversions by\n'
      '   Sheldon B. Michaels / Windell H. Oskay. SIL Open Font License 1.1 (OFL-EMS.txt). Generated by gen-glyphs.py. */')
print('window.SCRIPT_GLYPHS = ' + json.dumps(out, separators=(',', ':')) + ';')
