// Regenerates media/glyphs.js: the lockup's letter outlines for the Three.js extrusion (Archivo, OFL). Needs fontkit (npm i fontkit).
//   node gen-glyphs.js > glyphs.js        (run from a/media or b/media; reads ../assets/fonts/Archivo.ttf)
// Output: window.LOGO_GLYPHS = { title:{upm,cap,g,k}, tag:{upm,cap,g,k} }, g = {ch:[advance, path, inkMinX, inkMaxX]}, k = {pair:kern}.
// path = SVG commands in font units, y-down (baseline 0, cap top at -cap).
const fontkit = require('fontkit');
const f = fontkit.openSync(process.env.FONT || '../assets/fonts/Archivo.ttf');
const SETS = { title: { wdth: 78, wght: 900 }, tag: { wdth: 125, wght: 800 } };
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,'!?-&:#";
const r = (x) => Math.round(x);
const out = {};
for (const [name, axes] of Object.entries(SETS)) {
  const v = f.getVariation(axes), g = {}, k = {};
  for (const ch of chars) {
    const gl = v.glyphForCodePoint(ch.codePointAt(0));
    const cmds = gl.path.commands.map((c) => {
      const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
      const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
      return L + a.join(' ');
    }).join('');
    const b = gl.bbox;
    g[ch] = [r(gl.advanceWidth), cmds, ch === ' ' ? 0 : r(b.minX), ch === ' ' ? 0 : r(b.maxX)];
  }
  const L = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  for (const a of L) for (const b of L) {
    const lay = v.layout(a + b);
    const kern = r(lay.positions[0].xAdvance - v.glyphForCodePoint(a.codePointAt(0)).advanceWidth);
    if (kern) k[a + b] = kern;
  }
  out[name] = { upm: f.unitsPerEm, cap: r(v.glyphForCodePoint(72).bbox.maxY), axes, g, k };
}
process.stdout.write('/* Archivo outlines (OFL), title wdth 78/wght 900 and tag wdth 125/wght 800, generated by gen-glyphs.js with fontkit. */\n' +
  'window.LOGO_GLYPHS = ' + JSON.stringify(out) + ';\n');
