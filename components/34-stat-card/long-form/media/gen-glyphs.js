// Regenerates media/glyphs.js: the class letters on the 3D badge, as outlines for the Three.js extrusion.
//   FONTKIT=<path to fontkit> node gen-glyphs.js 100 900 > glyphs.js      (args: Archivo wdth, wght)
// Output: window.STAT_GLYPHS = {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX, inkMinY, inkMaxY]}}; path = SVG commands in
// font units, y-down (baseline 0, cap top at -cap).
const fontkit = require(process.env.FONTKIT || 'fontkit');
const f = fontkit.openSync(process.env.FONT || __dirname + '/../../../_shared/fonts/Archivo.ttf');
const [wdth, wght] = process.argv.slice(2).map(Number);
const v = f.getVariation({ wdth, wght });
const chars = process.env.CHARS || "SABCD+";
const r = (x) => Math.round(x);
const g = {};
for (const ch of chars) {
  const gl = v.glyphForCodePoint(ch.codePointAt(0));
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox; g[ch] = [r(gl.advanceWidth), cmds, r(b.minX), r(b.maxX), r(-b.maxY), r(-b.minY)];
}
const cap = r(v.glyphForCodePoint(72).bbox.maxY);
process.stdout.write('/* Archivo (OFL) wdth ' + wdth + ' wght ' + wght + ' outlines, generated by gen-glyphs.js with fontkit. */\n' +
  'window.STAT_GLYPHS = ' + JSON.stringify({ upm: f.unitsPerEm, cap, g }) + ';\n');
