// Regenerates media/glyphs.js: Archivo outlines for the Three.js step words and the coin's "$". Needs fontkit (npm i fontkit).
//   FONTKIT=/path/to/node_modules/fontkit FONT=../assets/fonts/Archivo.ttf node gen-glyphs.js > glyphs.js
// Output: window.STEP_GLYPHS = { <set>: {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX]}, k:{pair:kern}} }
// path = SVG commands in font units, y-down (baseline 0, cap top at -cap).
const fontkit = require(process.env.FONTKIT || 'fontkit');
const f = fontkit.openSync(process.env.FONT);
const SETS = { narrow: { wght: 900, wdth: 66 }, coin: { wght: 900, wdth: 100 } };
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,'!?-:#$+&/";
const r = (x) => Math.round(x);
const out = {};
for (const name in SETS) {
  const v = f.getVariation(SETS[name]);
  const g = {};
  for (const ch of chars) {
    const gl = v.glyphForCodePoint(ch.codePointAt(0));
    const cmds = gl.path.commands.map((c) => {
      const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
      const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
      return L + a.join(' ');
    }).join('');
    const b = gl.bbox;
    g[ch] = [r(gl.advanceWidth), cmds, ch === ' ' ? 0 : r(b.minX), ch === ' ' ? 0 : r(b.maxX)];
  }
  const k = {};
  const L = chars.replace(' ', '');
  for (const a of L) for (const b of L) {
    const lay = v.layout(a + b);
    const kern = r(lay.positions[0].xAdvance - v.glyphForCodePoint(a.codePointAt(0)).advanceWidth);
    if (kern) k[a + b] = kern;
  }
  out[name] = { upm: f.unitsPerEm, cap: r(v.glyphForCodePoint(72).bbox.maxY), axes: SETS[name], g, k };
}
process.stdout.write('/* Archivo outlines (OFL), ' + JSON.stringify(SETS) + ', generated by gen-glyphs.js with fontkit. */\n' +
  'window.STEP_GLYPHS = ' + JSON.stringify(out) + ';\n');
