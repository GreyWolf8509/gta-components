// Regenerates media/glyphs.js: Archivo digit outlines for the Three.js applied dial numerals. Needs fontkit.
//   FONTKIT=/path/to/node_modules/fontkit FONT=../assets/fonts/Archivo.ttf SETS='{"num":{"wght":800,"wdth":90}}' node gen-glyphs.js > glyphs.js
// Output: window.CLOCK_GLYPHS = { <set>: {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX]}} }; path = SVG commands, font units, y-down.
const fontkit = require(process.env.FONTKIT || 'fontkit');
const f = fontkit.openSync(process.env.FONT);
const SETS = JSON.parse(process.env.SETS);
const chars = "0123456789";
const r = (x) => Math.round(x * 10) / 10;
const out = {};
for (const name in SETS) {
  const v = f.getVariation(SETS[name]);
  const g = {};
  for (const ch of chars) {
    const gl = v.glyphForCodePoint(ch.codePointAt(0));
    const cmds = gl.path.commands.map((c) => {
      const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
      const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
      return L + a.join(' ');
    }).join('');
    const b = gl.bbox;
    g[ch] = [r(gl.advanceWidth), cmds, r(b.minX), r(b.maxX)];
  }
  out[name] = { upm: f.unitsPerEm, cap: r(v.glyphForCodePoint(72).bbox.maxY), fig: r(v.glyphForCodePoint(48).bbox.maxY), axes: SETS[name], g };
}
process.stdout.write('/* Archivo digit outlines (OFL), ' + JSON.stringify(SETS) + ', generated by gen-glyphs.js with fontkit. */\n' +
  'window.CLOCK_GLYPHS = ' + JSON.stringify(out) + ';\n');
