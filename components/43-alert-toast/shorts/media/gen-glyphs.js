// Regenerates media/glyphs.js: outlines of the amount glyphs for the inflated Three.js numerals. Needs fontkit (npm i fontkit).
//   FONT=../assets/fonts/Archivo.ttf AXES='{"wght":900,"wdth":100}' node gen-glyphs.js > glyphs.js
// Output: window.AMOUNT_GLYPHS = {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX]}}; path = SVG commands in font units, y-down.
const fontkit = require('fontkit');
const f = fontkit.openSync(process.env.FONT);
const v = f.getVariation(JSON.parse(process.env.AXES));
const chars = "$0123456789,.+KS";
const r = (x) => Math.round(x), g = {};
for (const ch of chars) {
  const gl = v.glyphForCodePoint(ch.codePointAt(0));
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox;
  g[ch] = [r(gl.advanceWidth), cmds, r(b.minX), r(b.maxX)];
}
console.log("/* Archivo " + process.env.AXES + " outlines (OFL), generated by gen-glyphs.js with fontkit. */");
console.log("window.AMOUNT_GLYPHS = " + JSON.stringify({ upm: f.unitsPerEm, cap: f.capHeight, g }) + ";");
