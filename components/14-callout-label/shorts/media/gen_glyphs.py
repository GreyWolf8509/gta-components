# Regenerates media/glyphs.js: Inter (OFL) at wght 900 / opsz 32, outlines for the Three.js extruded callout labels.
# usage: /usr/bin/python3 gen_glyphs.py > glyphs.js     (needs fontTools + brotli)
# Output: window.CALLOUT_GLYPHS = {upm, cap, g:{ch:[advance, svgPath, inkMinX, inkMaxX]}}; path in font units, y-down, baseline 0.
import json, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
here = os.path.dirname(os.path.abspath(__file__))
f = TTFont(os.path.join(here, '..', '..', '..', '_shared', 'fonts', 'Inter-normal.woff2'))
f = instancer.instantiateVariableFont(f, {'wght': 900, 'opsz': 32})
gs = f.getGlyphSet(); cmap = f.getBestCmap(); hm = f['hmtx']
chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 $.,'!?-+%#&"
out = {}
for ch in chars:
    gn = cmap[ord(ch)]; adv = hm[gn][0]
    sp = SVGPathPen(gs, ntos=lambda v: str(int(round(v))))
    gs[gn].draw(TransformPen(sp, (1, 0, 0, -1, 0, 0)))
    bp = BoundsPen(gs); gs[gn].draw(bp); b = bp.bounds
    out[ch] = [adv, sp.getCommands(), int(b[0]) if b else 0, int(b[2]) if b else 0]
cap = f['OS/2'].sCapHeight
print("/* Inter (OFL) wght 900 / opsz 32 outlines, generated by gen_glyphs.py with fontTools. */")
print("window.CALLOUT_GLYPHS = " + json.dumps({'upm': f['head'].unitsPerEm, 'cap': cap, 'g': out}, separators=(',', ':')) + ";")
