"""r04 local matte touch-up for A (the r03 critic's matte-leak defect). Run once after prep_freeze.py:

    /usr/bin/python3 fix_matte.py <a-dir>

The model cutout took two background fragments along Franklin's edge:
  - left shoulder (frame y 546-626): a dark palm frond above the shoulder and a 2-7 px sliver of Lamar's white tee below it;
  - right hem (frame y 738-882): the dark window frame and white wall of the house behind his sleeve.
Both are cut back to the hoodie edge measured on frz.png (luminance + warmth steps, see the point lists), with a 1.6 px
antialiased edge. Nothing else in subj.png changes. outline.js (the keyline) is re-traced from the new matte with exactly the
code in prep_freeze.py, so the keyline moves only where the matte moved.
"""
import sys, os, json
import numpy as np, cv2
from PIL import Image

md = os.path.join(sys.argv[1], "media")
im = np.asarray(Image.open(os.path.join(md, "subj.png")).convert("RGBA")).copy()
H, W = im.shape[:2]
a = im[..., 3].astype(np.float32) / 255.0
X = np.arange(W, dtype=np.float32)[None, :]

# left shoulder: keep x >= Lx(y)  (frame px; measured hoodie edge)
LP = [(546, 1032.0), (549, 1028.5), (552, 1024.5), (555, 1020.5), (558, 1017.0), (561, 1014.5), (564, 1012.0), (567, 1010.0),
      (570, 1008.2), (574, 1007.0), (578, 1006.0), (582, 1004.8), (586, 1002.8), (590, 1001.2), (594, 1000.0), (598, 998.0),
      (602, 996.0), (606, 993.5), (610, 991.0), (614, 988.8), (618, 987.2), (622, 985.8), (626, 984.5)]
ys = np.arange(LP[0][0], LP[-1][0] + 1)
lx = np.interp(ys, [p[0] for p in LP], [p[1] for p in LP]).astype(np.float32)
x0, x1 = 930, 1060
k = np.clip((X[:, x0:x1] - lx[:, None]) / 1.6 + 0.5, 0, 1)
a[ys[0]:ys[-1] + 1, x0:x1] *= k

# right hem: keep x <= Rx(y)
RP = [(738, 1604.0), (744, 1604.5), (750, 1605.0), (756, 1605.5), (762, 1607.5), (768, 1608.5), (774, 1609.5), (780, 1611.0),
      (786, 1611.5), (792, 1612.0), (798, 1612.5), (804, 1614.0), (810, 1614.5), (816, 1615.5), (822, 1616.0), (828, 1616.5),
      (834, 1617.0), (850, 1620.5), (866, 1624.5), (882, 1632.0)]
ys = np.arange(RP[0][0], RP[-1][0] + 1)
rx = np.interp(ys, [p[0] for p in RP], [p[1] for p in RP]).astype(np.float32)
x0, x1 = 1580, 1700
k = np.clip((rx[:, None] - X[:, x0:x1]) / 1.6 + 0.5, 0, 1)
a[ys[0]:ys[-1] + 1, x0:x1] *= k

im[..., 3] = (np.clip(a, 0, 1) * 255 + 0.5).astype(np.uint8)
Image.fromarray(im).save(os.path.join(md, "subj.png"), optimize=True)

# ---- keyline: identical to prep_freeze.py's tracer (a > 0.5 on the saved 8-bit alpha)
m = (im[..., 3] >= 128).astype(np.uint8)
cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
c = max(cs, key=cv2.contourArea)[:, 0, :].astype(np.float32)
c = cv2.approxPolyDP(c.reshape(-1, 1, 2), 1.2, True)[:, 0, :]
ti = int(np.argmin(c[:, 1] + np.abs(c[:, 0] - c[:, 0].mean()) * 0.02))
c = np.roll(c, -ti, axis=0)
onedge = lambda p: p[0] <= 2 or p[0] >= W - 3 or p[1] >= H - 3 or p[1] <= 2
def chain(pts):
    out = []
    for p in pts:
        if onedge(p):
            break
        out.append(p)
    return out
fwd = chain(list(c) + [c[0]])
bwd = chain([c[0]] + list(c[::-1]))
def d_of(pts):
    pts = [(round(float(x), 1), round(float(y), 1)) for x, y in pts]
    return "M" + " L".join("%s %s" % p for p in pts), float(sum(np.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]) for i in range(len(pts) - 1)))
if np.mean([p[0] for p in fwd]) > np.mean([p[0] for p in bwd]):
    fwd, bwd = bwd, fwd
dl, ll = d_of(fwd)
dr, lr = d_of(bwd)
bx, by, bw, bh = cv2.boundingRect(m)
out = {"W": W, "H": H, "top": [float(c[0][0]), float(c[0][1])], "left": dl, "right": dr, "lenL": round(ll, 1), "lenR": round(lr, 1),
       "bbox": [int(bx), int(by), int(bx + bw), int(by + bh)]}
with open(os.path.join(md, "outline.js"), "w") as f:
    f.write("/* generated by prep_freeze.py: the subject keyline, crown -> down each side (frame px). */\nwindow.FRZ_OUTLINE = " + json.dumps(out) + ";\n")
print(json.dumps({k: out[k] for k in ("top", "lenL", "lenR", "bbox")}))
