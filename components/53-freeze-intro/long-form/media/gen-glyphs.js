// Regenerates media/glyphs.js (the title's outlines for the Three.js extrusion). Needs fontkit:
//   NODE_PATH=<dir with fontkit> AXES='{"wght":900,"wdth":88}' node gen-glyphs.js > glyphs.js
// Output: window.FRZ_GLYPHS = {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX]}, k:{pair:kern}}; path = SVG commands in
// font units, y-down (baseline 0, cap top at -cap).
const fontkit = require('fontkit');
const f = fontkit.openSync(process.env.FONT || __dirname + '/../../../_shared/fonts/Archivo.ttf');
const axes = JSON.parse(process.env.AXES || '{"wght":900,"wdth":88}');
const v = f.getVariation(axes);
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,'!?-&:#";
const r = (x) => Math.round(x);
const g = {};
for (const ch of chars) {
  const gl = v.glyphForCodePoint(ch.codePointAt(0));
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox; g[ch] = [r(gl.advanceWidth), cmds, ch === " " ? 0 : r(b.minX), ch === " " ? 0 : r(b.maxX)];
}
const k = {};
const L = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
for (const a of L) for (const b of L) {
  const lay = v.layout(a + b);
  const kern = r(lay.positions[0].xAdvance - v.glyphForCodePoint(a.codePointAt(0)).advanceWidth);
  if (kern) k[a + b] = kern;
}
const bb = v.glyphForCodePoint(72).bbox;
process.stdout.write("/* Archivo.ttf " + JSON.stringify(axes) + " outlines (OFL), generated by gen-glyphs.js with fontkit. */\nwindow.FRZ_GLYPHS = " +
  JSON.stringify({ upm: f.unitsPerEm, cap: r(bb.maxY), g, k }) + ";\n");
