// Regenerates media/glyphs.js (the keyword's outlines for the Three.js extrusion). Needs fontkit (npm i fontkit).
//   A: FONT=Inter.ttf (Inter-normal.woff2 decompressed with fontTools: TTFont(p).flavor=None; save) AXES='{"wght":900,"opsz":32}' node gen-glyphs.js > glyphs.js
//   B: FONT=../assets/fonts/Archivo.ttf  AXES='{"wght":900,"wdth":64}' node gen-glyphs.js > glyphs.js
// Output: window.KEY_GLYPHS = {upm, cap, g:{ch:[advance, path, inkMinX, inkMaxX]}, k:{pair:kern}}
// path = SVG commands in font units, y-down (baseline 0, cap top at -cap).
const fontkit = require('fontkit');
const f = fontkit.openSync(process.env.FONT);
const v = f.getVariation(JSON.parse(process.env.AXES));
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,'!?-$’";
const r = (x) => Math.round(x);
const g = {};
for (const ch of chars) {
  const gl = v.glyphForCodePoint(ch.codePointAt(0));
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox;
  g[ch] = [r(gl.advanceWidth), cmds, ch === ' ' ? 0 : r(b.minX), ch === ' ' ? 0 : r(b.maxX)];
}
const k = {};
const L = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.,'!?$’";
for (const a of L) for (const b of L) {
  const lay = v.layout(a + b);
  const kern = r(lay.positions[0].xAdvance - v.glyphForCodePoint(a.codePointAt(0)).advanceWidth);
  if (kern) k[a + b] = kern;
}
const cap = r(v.glyphForCodePoint(72).bbox.maxY);
const xh = r(v.glyphForCodePoint(120).bbox.maxY);
process.stdout.write('/* ' + (process.env.FONT || '').split('/').pop() + ' ' + process.env.AXES + ' outlines (OFL), generated by gen-glyphs.js with fontkit. */\n' +
  'window.KEY_GLYPHS = ' + JSON.stringify({ upm: f.unitsPerEm, cap, xh, g, k }) + ';\n');
