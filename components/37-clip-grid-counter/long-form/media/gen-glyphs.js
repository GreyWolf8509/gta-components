// Regenerates media/glyphs.js: Inter (OFL) digit outlines at wght 900 / opsz 32, tabular figures, for the extruded 3D counter.
// Inter.ttf = assets/fonts/Inter-normal.woff2 decompressed with fontTools (TTFont(p).flavor=None; save). Needs fontkit:  NODE_PATH=<dir with fontkit> FONT=Inter.ttf node gen-glyphs.js > glyphs.js
// Output: window.COUNTER_GLYPHS = {upm, cap, g:{digit:[advance, svgPath(y-down, baseline 0, font units), inkMinX, inkMaxX, inkMinY, inkMaxY]}}
const fontkit = require('fontkit');
const f = fontkit.openSync(process.env.FONT);
const v = f.getVariation({ wght: 900, opsz: 32 });
const r = (x) => Math.round(x);
const g = {};
for (const ch of "0123456789") {
  const run = v.layout(ch, ['tnum']);
  const gl = run.glyphs[0];
  const cmds = gl.path.commands.map((c) => {
    const a = c.args.map((n, i) => (i % 2 ? -r(n) : r(n)));
    const L = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }[c.command];
    return L + a.join(' ');
  }).join('');
  const b = gl.bbox;
  g[ch] = [r(gl.advanceWidth), cmds, r(b.minX), r(b.maxX), r(b.minY), r(b.maxY)];
}
const cap = r(v.glyphForCodePoint(72).bbox.maxY);
process.stdout.write('/* Inter (OFL) wght 900 / opsz 32 tabular digits, generated by gen-glyphs.js with fontkit. */\n' +
  'window.COUNTER_GLYPHS = ' + JSON.stringify({ upm: f.unitsPerEm, cap, g }) + ';\n');
